// Kopiranje teksta (npr. adrese za drugu aplikaciju). `navigator.clipboard` postoji
// samo u sigurnom kontekstu i uz dozvolu, pa je rezerva stari način sa skrivenim
// poljem. Vraća true ako je kopirano.
export const copyText = async (text: string): Promise<boolean> => {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // padamo na rezervu ispod
  }

  try {
    const field = document.createElement("textarea");
    field.value = text;
    field.setAttribute("readonly", "");
    field.style.position = "fixed";
    field.style.opacity = "0";
    document.body.appendChild(field);
    field.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(field);
    return ok;
  } catch {
    return false;
  }
};
